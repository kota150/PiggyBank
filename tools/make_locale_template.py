"""Regenerate Locales/_template.lua from the strings used in the addon.

Run from the repo root after changing any text:  python3 tools/make_locale_template.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "PiggyBank.lua").read_text(encoding="utf-8")

keys = []
def add(key):
    if key not in keys:
        keys.append(key)

for key in re.findall(r'L\["((?:[^"\\]|\\.)*)"\]', src):
    add(key)

# Stat labels are looked up as L[stat[1]], so pick them out of the STAT_ROWS table.
stat_block = re.search(r"local STAT_ROWS = \{(.*?)\n\}", src, re.S).group(1)
for key in re.findall(r'^\s*\{ "((?:[^"\\]|\\.)*)",', stat_block, re.M):
    add(key)

lines = [
    "-- Translation template for Piggy Bank. Generated by tools/make_locale_template.py; don't edit.",
    "-- Copy this file to Locales/<locale>.lua (deDE, frFR, esES, esMX, ruRU, ptBR, itIT, koKR, zhCN, zhTW),",
    "-- change the locale on the GetLocale line, translate the right-hand side of each line,",
    "-- and delete any line you don't translate (it falls back to English). See TRANSLATING.md.",
    "",
    "local _, ns = ...",
    'if GetLocale() ~= "xxXX" then return end',
    "local L = ns.L",
    "",
]
for key in keys:
    lines.append(f'L["{key}"] = "{key}"')
lines += [
    "",
    "-- The puns are whole lists you can replace with your own. They don't need to be literal",
    "-- translations; jokes that work in your language are better.",
    "-- ns.SCOLDS = { \"...\", \"...\" }",
    "-- ns.HEADS_UPS = { \"...\", \"...\" }",
    "",
]
out = root / "Locales" / "_template.lua"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {len(keys)} strings to {out.relative_to(root)}")
